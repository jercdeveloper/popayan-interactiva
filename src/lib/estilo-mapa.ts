/** Capas del mapa base que usan íconos (sprites): no se usan, la app dibuja sus propios marcadores. */
const SIN_ICONOS = new Set(['pois', 'roads_shields', 'roads_oneway']);

export function estiloMapa(
  tema: TemaMapa,
  origen: string,
  paleta: { claro: Partial<Flavor>; oscuro: Partial<Flavor> } = { claro: CIUDAD_BLANCA, oscuro: NOCHE },
): StyleSpecification {
  const base = namedFlavor(tema === 'claro' ? 'light' : 'dark');
  const sabor: Flavor = { ...base, ...(tema === 'claro' ? paleta.claro : paleta.oscuro) };
  return {
    version: 8,
    glyphs: `${origen}/mapa/fuentes/{fontstack}/{range}.pbf`,
    sources: {
      protomaps: {
        type: 'vector',
        tiles: [`${origen}/mapa/teselas/{z}/{x}/{y}.pbf`],
        minzoom: 6,
        maxzoom: 15,
        attribution: '<a href="https://www.openstreetmap.org/copyright">© OpenStreetMap</a> · <a href="https://protomaps.com">Protomaps</a>',
      },
    },
    layers: layers('protomaps', sabor, { lang: 'es' }).filter((capa) => !SIN_ICONOS.has(capa.id)),
  };
}
